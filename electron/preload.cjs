const { contextBridge, ipcRenderer, webUtils } = require('electron')

contextBridge.exposeInMainWorld('api', {
  mica: process.argv.includes('--md-mica=1'),
  openDialog: () => ipcRenderer.invoke('open-dialog'),
  readFile: (p) => ipcRenderer.invoke('read-file', p),
  saveFile: (opts) => ipcRenderer.invoke('save-file', opts),
  pickImage: () => ipcRenderer.invoke('pick-image'),
  confirmDiscard: () => ipcRenderer.invoke('confirm-discard'),
  saveDraft: (key, md) => ipcRenderer.send('draft-save', key, md),
  loadDraft: (key) => ipcRenderer.invoke('draft-load', key),
  clearDraft: (key) => ipcRenderer.send('draft-clear', key),
  reportState: (state) => ipcRenderer.send('doc-state', state),
  closeNow: () => ipcRenderer.send('close-now'),
  openPath: (p) => ipcRenderer.send('open-path', p),
  openExternal: (url) => ipcRenderer.send('open-external', url),
  setTheme: (t) => ipcRenderer.send('set-theme', t),
  getPathForFile: (file) => webUtils.getPathForFile(file),
  // 连续写作
  listFolder: (dir) => ipcRenderer.invoke('list-folder', dir),
  watchFolder: (dir) => ipcRenderer.send('watch-folder', dir),
  onFolderChanged: (cb) => ipcRenderer.on('folder-changed', (_e, dir) => cb(dir)),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  statPath: (p) => ipcRenderer.invoke('stat-path', p),
  pickMarkdown: (title, defaultPath) => ipcRenderer.invoke('pick-markdown', title, defaultPath),
  resolveLink: (from, href) => ipcRenderer.invoke('resolve-link', from, href),
  focusIfOpen: (p) => ipcRenderer.invoke('focus-if-open', p),
  indexElsewhere: (p, payload) => ipcRenderer.invoke('index-elsewhere', p, payload),
  onApplyIndex: (cb) => ipcRenderer.on('apply-index', (_e, payload) => cb(payload)),
  openButtonMenu: () => ipcRenderer.send('open-button-menu'),
  captureRect: (rect) => ipcRenderer.invoke('capture-rect', rect),
  memoryGet: (kind, p) => ipcRenderer.invoke('memory-get', kind, p),
  rootFor: (p) => ipcRenderer.invoke('memory-root-for', p),
  memorySet: (kind, p, value) => ipcRenderer.send('memory-set', kind, p, value),
  onOpenDoc: (cb) => ipcRenderer.on('open-doc', (_e, doc) => cb(doc)),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd) => cb(cmd)),
})
